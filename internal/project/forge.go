package project

import (
	"fmt"
	"net/url"
	"path/filepath"
	"regexp"
	"strings"
)

// Forge kinds. Gitea and Forgejo run GitHub Actions syntax (act_runner /
// forgejo-runner), with the differences handled in the template.
const (
	GitHub  = "github"
	Gitea   = "gitea"
	Forgejo = "forgejo"
)

// Kinds are the forge kinds init can generate for, in menu order.
var Kinds = []string{GitHub, Gitea, Forgejo}

// Forge is where the project's repository lives: github.com or a
// registered instance (custom domain). The zero value is github.com.
type Forge struct {
	Name string `yaml:"name"`
	Kind string `yaml:"kind"`
	URL  string `yaml:"url"`
	// ActionsURL is where `uses:` actions are fetched from (a mirror, e.g.
	// https://git.acme.com/mirror). Empty: the instance default, which is
	// github.com on Gitea; Forgejo defaults to data.forgejo.org, which lacks
	// some of the actions used, so it falls back to https://github.com.
	ActionsURL string `yaml:"actions_url,omitempty"`
	// Runner is the runs-on label (default ubuntu-latest).
	Runner string `yaml:"runner,omitempty"`
}

// GitHubCom is the built-in forge.
var GitHubCom = Forge{Name: "github", Kind: GitHub, URL: "https://github.com"}

func (f Forge) kind() string {
	if f.Kind == "" {
		return GitHub
	}
	return f.Kind
}

// IsGitHub: the original workflow (separate build and deploy jobs, artifact
// in between, `gh` for the release).
func (f Forge) IsGitHub() bool { return f.kind() == GitHub }

// KindName is the display name of the kind.
func KindName(kind string) string {
	switch kind {
	case GitHub, "":
		return "GitHub"
	case Gitea:
		return "Gitea"
	case Forgejo:
		return "Forgejo"
	}
	return kind
}

// Label is "name (Kind, host)" for menus and summaries.
func (f Forge) Label() string {
	if f.Name == "" {
		return GitHubCom.Label()
	}
	return f.Name + " (" + KindName(f.kind()) + ", " + f.Host() + ")"
}

// Host is the host[:port] of URL, lowercased.
func (f Forge) Host() string {
	u, err := url.Parse(f.URL)
	if err != nil || u.Host == "" {
		return strings.ToLower(f.URL)
	}
	return strings.ToLower(u.Host)
}

// WorkflowDir is where the forge reads workflows from, relative to the
// repository root.
func (f Forge) WorkflowDir() string {
	switch f.kind() {
	case Gitea:
		return filepath.Join(".gitea", "workflows")
	case Forgejo:
		return filepath.Join(".forgejo", "workflows")
	}
	return filepath.Join(".github", "workflows")
}

// WorkflowPath is the deploy workflow generated by init.
func (f Forge) WorkflowPath(dir string) string {
	return filepath.Join(dir, f.WorkflowDir(), "deploy.yml")
}

func (f Forge) RunsOn() string {
	if f.Runner == "" {
		return "ubuntu-latest"
	}
	return f.Runner
}

func (f Forge) actionsURL() string {
	if f.ActionsURL == "" && f.kind() == Forgejo {
		return "https://github.com"
	}
	return strings.TrimSuffix(f.ActionsURL, "/")
}

// Uses renders p for this forge: owner/repo@sha, or a full URL when the
// actions come from somewhere other than the instance default.
func (f Forge) Uses(p Pin) string {
	if f.IsGitHub() || f.actionsURL() == "" {
		return p.Uses()
	}
	return f.actionsURL() + "/" + p.Uses()
}

var forgeNameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]*$`)

// Validate checks a forge before it is registered or used.
func (f Forge) Validate() error {
	if !forgeNameRe.MatchString(f.Name) {
		return fmt.Errorf("nome de instância inválido: %q (use letras minúsculas, números, ., - e _)", f.Name)
	}
	known := false
	for _, k := range Kinds {
		known = known || f.Kind == k
	}
	if !known {
		return fmt.Errorf("tipo de instância inválido: %q (use %s)", f.Kind, strings.Join(Kinds, ", "))
	}
	for _, s := range []struct{ name, v string }{{"url", f.URL}, {"actions-url", f.ActionsURL}} {
		if s.v == "" && s.name == "actions-url" {
			continue
		}
		u, err := url.Parse(s.v)
		if err != nil || (u.Scheme != "https" && u.Scheme != "http") || u.Host == "" {
			return fmt.Errorf("%s inválida: %q (ex.: https://git.empresa.com)", s.name, s.v)
		}
	}
	if f.Runner != "" && strings.ContainsAny(f.Runner, " \t\n:#\"'") {
		return fmt.Errorf("label do runner inválido: %q", f.Runner)
	}
	return nil
}

var (
	scpRemoteRe = regexp.MustCompile(`^[^@/]+@([^:/]+):`) // git@host:owner/repo
)

// RemoteHost extracts the host of a git remote URL (https, ssh:// or the
// scp-like git@host:path form). The port of an ssh remote is dropped: it
// is the SSH port, not the web one.
func RemoteHost(remote string) string {
	remote = strings.TrimSpace(remote)
	if m := scpRemoteRe.FindStringSubmatch(remote); m != nil && !strings.Contains(remote, "://") {
		return strings.ToLower(m[1])
	}
	u, err := url.Parse(remote)
	if err != nil || u.Host == "" {
		return ""
	}
	if u.Scheme == "ssh" || u.Scheme == "git" {
		return strings.ToLower(u.Hostname())
	}
	return strings.ToLower(u.Host)
}

// MatchForge finds the forge whose host matches the remote's. An ssh
// remote matches on the hostname alone (its port is the SSH one).
func MatchForge(forges []Forge, remote string) (Forge, bool) {
	host := RemoteHost(remote)
	if host == "" {
		return Forge{}, false
	}
	for _, f := range forges {
		h := f.Host()
		if h == host {
			return f, true
		}
		if name, _, ok := strings.Cut(h, ":"); ok && name == host {
			return f, true
		}
	}
	return Forge{}, false
}
